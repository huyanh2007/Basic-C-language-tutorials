//Kiểu ký tự trong C 
#include<stdio.h>

int main() {
	// Khai báo c kiểu ký tự và gán c thành x
    char c = 'x';
    //hiển thị c ra màn hình
    printf("%c\n",c);
    //Ký tự bản chất là 1 số nguyên , có thể cộng hoặc trừ để thay đổi các ký tự 
    char a = 'a';
    printf("%c" , a + 3 ); //Chuyển từ a thành d bằng cách cộng thêm 3
	return 0;
}